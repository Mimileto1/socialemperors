# Check for valid village
# The reason why this was implemented is to warn the user if a save game from Social Wars was used by accident

def is_valid_village(save: dict):
    if "playerInfo" not in save or "maps" not in save or "privateState" not in save:
        # These are obvious
        return False
    for map in save["maps"]:
        if "oil" in map or "steel" in map:
            return False
        if "stone" not in map or "food" not in map:
            return False
        if "items" not in map:
            return False
        if type(map["items"]) != list:
            return False

    return True

# Persistency

def save_session(USERID: str):
    file = f"{USERID}.save.json"
    print(f" * Saving village at {file}... ", end='')
    village = session(USERID)
    if village is None:
        raise KeyError(f"No save exists for player {USERID!r}")

    if durable.DATABASE_URL:
        durable.save_file(file, village)
        return
    os.makedirs(SAVES_DIR, exist_ok=True)
    target = os.path.join(SAVES_DIR, file)
    temp_path = None
    try:
        # Write beside the target so os.replace is atomic, including on Windows.
        with tempfile.NamedTemporaryFile(
            mode='w', encoding='utf-8', newline='\n', dir=SAVES_DIR,
            prefix=f".{USERID}.", suffix='.tmp', delete=False
        ) as f:
            temp_path = f.name
            json.dump(village, f, indent=4, ensure_ascii=False)
            f.flush()
            os.fsync(f.fileno())
        os.replace(temp_path, target)
        temp_path = None
    finally:
        if temp_path and os.path.exists(temp_path):
            os.remove(temp_path)
    print("Done.")
